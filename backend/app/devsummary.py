"""'Send to my developer': a copyable technical summary of one run, in Markdown."""

from typing import Any

from .failures import FAILURE_TYPES

SNIPPETS: dict[str, str] = {
    "price_image_only": '<span class="price">$24.00</span>  <!-- price as text, not inside an image -->',
    "price_missing": '<span class="price">$24.00</span>',
    "jsonld_missing": """<script type="application/ld+json">
{"@context": "https://schema.org", "@type": "Product", "name": "PRODUCT NAME", "sku": "SKU",
 "offers": {"@type": "Offer", "price": "24.00", "priceCurrency": "USD",
            "availability": "https://schema.org/InStock"}}
</script>""",
    "jsonld_incomplete": '"offers": {"price": "24.00", "priceCurrency": "USD", "availability": "https://schema.org/InStock"}',
    "stock_missing": '<p class="stock">In stock</p>  <!-- and offers.availability in JSON-LD -->',
    "currency_missing": '<span class="price">$24.00</span>  <!-- and "priceCurrency": "USD" in JSON-LD -->',
    "buy_button_nonsemantic": '<button type="submit" class="buy">Buy now</button>  <!-- replace clickable <div>s -->',
    "buy_button_missing": '<button type="submit">Add to cart</button>',
    "image_alt_missing": '<img src="mug.jpg" alt="Speckled Stoneware Mug">',
    "oos_still_buyable": '<button type="submit" disabled>Sold out</button>',
    "buy_button_covered": "/* cookie banner as a bottom bar that never overlaps the buy controls */\n"
                          ".cookie-banner { position: fixed; inset: auto 0 0 0; max-height: 72px; }",
}


def developer_summary(run: dict[str, Any]) -> str:
    card = run.get("scorecard") or {}
    lines = [
        f"# GhostShopper report: run {run['id']}",
        "",
        f"- Store: {run['store_url']}",
        f"- Platform: {run.get('platform') or 'unknown'}",
        f"- Mode: {'live store (browse-only, no payment)' if run.get('live') else 'GhostShopper demo store'}",
        f"- Agent: {run['llm']} ({run.get('model') or '-'}), browser: {run['browser']}",
        f"- Outcome: {run['outcome']} (end reason: {run.get('end_reason')})",
        f"- Score: {card.get('total')}/100 over {card.get('possible')} points the store controls "
        f"(rules {card.get('rules_version')})",
        "",
        "## Failures to fix (most points first)",
        "",
    ]
    fixes = [f for f in card.get("fixes", []) if f["status"] == "failed"]
    if not fixes:
        lines.append("None.")
    for i, f in enumerate(fixes, 1):
        ev = f.get("evidence") or {}
        lines += [
            f"### {i}. {f['title']} ({f['points']} pts, `{f['check']}` / `{f.get('code')}`)",
            "",
            f"- What we saw: {f.get('reason')}",
            f"- Page: {ev.get('url', '-')}",
            f"- Selector: `{ev.get('selector')}`" if ev.get("selector") else "- Selector: -",
            f"- Screenshot: {ev.get('screenshot', '-')}",
            f"- Fix: {f['fix']}",
        ]
        snippet = SNIPPETS.get(f.get("code") or "")
        if snippet:
            lines += ["", "```html", snippet, "```"]
        lines.append("")
    excluded = card.get("not_store_fault") or []
    if excluded:
        lines += ["## Not counted against the store", ""]
        for n in excluded:
            ft = FAILURE_TYPES.get(n.get("code") or "")
            lines.append(f"- {n['title']} (`{n['check']}`, {n['points']} pts): {n.get('reason') or ''} "
                         f"{ft.fix if ft else ''}".rstrip())
        lines.append("")
    untested = [f for f in card.get("fixes", []) if f["status"] == "not_tested"]
    if untested:
        lines += ["## Not tested in this run", ""]
        lines += [f"- {f['title']} (`{f['check']}`): {f.get('reason') or ''}" for f in untested]
        lines.append("")
    lines.append("Generated by GhostShopper. Scores come from deterministic checks on what the browser saw.")
    return "\n".join(lines)
